void main() {
    // 3-Autoboxing and Unboxing
    // Java's automatic conversion between primitive types and their wrapper classes
    Integer obj = 42; // Autoboxing int -> Integer
    int num = obj; // Unboxing Integer -> int
    System.out.println(num);
}
